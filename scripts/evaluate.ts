// Measures matching accuracy on the test questions in database/seed/test-questions.json.
//   npm run evaluate            run the held-out test set and the dev set, write docs/results/
// Works without MySQL: it builds the same matcher index from the seed files.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { evaluate, type TestCase, type TestRow, type TestSummary } from "../src/lib/evaluate";
import { formatScore } from "../src/lib/format";
import { buildIndex, type KnowledgeEntry, type LanguageRule, type Thresholds } from "../src/lib/nlp/matcher";

const ROOT = join(__dirname, "..");
const read = <T>(name: string): T => JSON.parse(readFileSync(join(ROOT, "database", "seed", name), "utf8")) as T;

type SeedEntry = { key: string; category: string; question: string; variants: string[] };
type SeedTest = { question: string; expect: string | null; style: string; set: "test" | "dev" };

const entries = read<SeedEntry[]>("knowledge-base.json");
const rules = read<LanguageRule[]>("language-rules.json");
const tests = read<SeedTest[]>("test-questions.json");
const settings = read<{ answer_threshold: number; suggest_threshold: number }>("settings.json");
const thresholds: Thresholds = { answer: settings.answer_threshold, suggest: settings.suggest_threshold };

const idOf = new Map(entries.map((e, i) => [e.key, i + 1]));
const kb: KnowledgeEntry[] = entries.map((e, i) => ({
  id: i + 1,
  question: e.question,
  variants: e.variants,
  category: e.category,
  smallTalk: e.category === "chat-basics",
}));
const index = buildIndex(kb, rules);
const questionOf = (id: number) => entries[id - 1]?.question ?? `#${id}`;

const casesFor = (set: "test" | "dev"): TestCase[] =>
  tests.filter((t) => t.set === set).map((t) => ({ question: t.question, expectId: t.expect ? idOf.get(t.expect)! : null, style: t.style }));

const pct = (n: number) => `${(n * 100).toFixed(1)}%`;

function markdown(title: string, rows: TestRow[], s: TestSummary): string {
  const lines = [
    `# ${title}`,
    "",
    `Thresholds: answer at ${thresholds.answer.toFixed(2)} or more, suggest from ${thresholds.suggest.toFixed(2)}. Generated by \`npm run evaluate\`.`,
    "",
    "| # | Test question | Style | Expected | Bot result | Score | Outcome |",
    "|---|---|---|---|---|---|---|",
    ...rows.map((r, i) => `| ${i + 1} | ${r.question} | ${r.style ?? ""} | ${r.expected} | ${r.got} | ${formatScore(r.score)} | ${r.outcome}${r.correct ? "" : " (x)"} |`),
    "",
    `**Correct: ${s.correct} of ${s.total} (${pct(s.accuracy)}).** In scope: ${s.inScopeCorrect} of ${s.inScope} answered correctly. Out of scope: ${s.outOfScopeCorrect} of ${s.outOfScope} correctly sent to the fallback.`,
    "",
    `Precision (answers given that were right): ${pct(s.precision)}. Recall (in-scope questions answered correctly): ${pct(s.recall)}.`,
    "",
    "| Outcome | Count |",
    "|---|---|",
    ...Object.entries(s.counts).map(([k, v]) => `| ${k} | ${v} |`),
    "",
  ];
  return lines.join("\n");
}

function csv(rows: TestRow[]): string {
  const esc = (v: string | number | boolean | null) => `"${String(v ?? "").replace(/"/g, '""')}"`;
  return [
    ["no", "question", "style", "expected", "bot_result", "score", "outcome", "correct"].join(","),
    ...rows.map((r, i) => [i + 1, r.question, r.style, r.expected, r.got, r.score.toFixed(3), r.outcome, r.correct].map(esc).join(",")),
  ].join("\n");
}

const outDir = join(ROOT, "docs", "results");
mkdirSync(outDir, { recursive: true });

// While tuning, run with --dev so the held-out test set is not looked at.
const sets = process.argv.includes("--dev") ? (["dev"] as const) : (["test", "dev"] as const);
for (const set of sets) {
  const { rows, summary } = evaluate(index, casesFor(set), thresholds, questionOf);
  const title = set === "test" ? "Test results: 30 held-out questions" : "Development set results (used to tune the thresholds)";
  writeFileSync(join(outDir, `evaluation-${set}.md`), markdown(title, rows, summary));
  writeFileSync(join(outDir, `evaluation-${set}.csv`), csv(rows));

  console.log(`\n${title}`);
  console.table(rows.map((r) => ({ question: r.question.slice(0, 48), score: formatScore(r.score), outcome: r.outcome })));
  console.log(`Correct ${summary.correct}/${summary.total} (${pct(summary.accuracy)}), precision ${pct(summary.precision)}, recall ${pct(summary.recall)}`);
}

// Threshold sweep on the dev set: shows why the answer threshold was chosen.
const sweep = ["# Threshold sweep (development set)", "", "| Answer threshold | Correct | Accuracy | Wrong answers | False answers | Missed or suggested |", "|---|---|---|---|---|---|"];
for (let t = 0.3; t <= 0.701; t += 0.05) {
  const th = { answer: Number(t.toFixed(2)), suggest: Math.min(thresholds.suggest, Number(t.toFixed(2))) };
  const { summary: s } = evaluate(index, casesFor("dev"), th, questionOf);
  sweep.push(`| ${th.answer.toFixed(2)} | ${s.correct}/${s.total} | ${pct(s.accuracy)} | ${s.counts["wrong answer"]} | ${s.counts["false answer"]} | ${s.counts.missed + s.counts.suggested} |`);
}
writeFileSync(join(outDir, "threshold-sweep.md"), `${sweep.join("\n")}\n`);
console.log(`\n${sweep.join("\n")}\n\nWrote docs/results/evaluation-test.md, evaluation-dev.md and threshold-sweep.md`);
