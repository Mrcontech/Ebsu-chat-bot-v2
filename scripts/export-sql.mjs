// Writes database/ebsu_chatbot.sql: the schema plus all starting data as plain SQL.
// Use it as a backup way to set up the database by hand in phpMyAdmin:
//   phpMyAdmin > New > create "ebsu_chatbot" > Import > choose this file > Go
// The admin password inside it is the default (ebsu-admin-2026); change it after logging in.
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { ROOT } from "./lib/env.mjs";
import { loadSeed } from "./lib/seed-data.mjs";

const bcrypt = (await import("bcryptjs")).default;
const seed = loadSeed();
const q = (v) => (v === null || v === undefined ? "NULL" : `'${String(v).replace(/\\/g, "\\\\").replace(/'/g, "''").replace(/\r?\n/g, "\\n")}'`);

const out = [
  "-- EBSU Enquiry Bot: schema and starting data",
  "-- Generated by `npm run db:export`. Import into an empty database called ebsu_chatbot.",
  "",
  readFileSync(join(ROOT, "database", "schema.sql"), "utf8"),
  "",
  "START TRANSACTION;",
];

seed.categories.forEach((c, i) => out.push(`INSERT INTO categories (id, slug, name, description, icon, sort_order) VALUES (${i + 1}, ${q(c.slug)}, ${q(c.name)}, ${q(c.description)}, ${q(c.icon)}, ${i + 1});`));
const cat = new Map(seed.categories.map((c, i) => [c.slug, i + 1]));
seed.offices.forEach((o, i) =>
  out.push(`INSERT INTO offices (id, slug, name, handles, email, phone, location, website, source_url) VALUES (${i + 1}, ${q(o.slug)}, ${q(o.name)}, ${q(o.handles)}, ${q(o.email)}, ${q(o.phone)}, ${q(o.location)}, ${q(o.website)}, ${q(o.source_url)});`),
);
const off = new Map(seed.offices.map((o, i) => [o.slug, i + 1]));
const qa = new Map();
seed.entries.forEach((e, i) => {
  const id = i + 1;
  qa.set(e.key, id);
  out.push(
    `INSERT INTO qa_pairs (id, ref_key, category_id, office_id, question, answer, source_url, source_note, is_featured) VALUES (${id}, ${q(e.key)}, ${cat.get(e.category)}, ${e.office ? off.get(e.office) : "NULL"}, ${q(e.question)}, ${q(e.answer)}, ${q(e.source_url)}, ${q(e.source_note)}, ${e.featured ? 1 : 0});`,
  );
  for (const v of e.variants ?? []) out.push(`INSERT INTO qa_variants (qa_id, phrasing) VALUES (${id}, ${q(v)});`);
});
for (const r of seed.rules) out.push(`INSERT INTO language_rules (phrase, canonical, kind) VALUES (${q(r.phrase)}, ${q(r.canonical)}, ${q(r.kind)});`);
for (const t of seed.tests) {
  out.push(
    `INSERT INTO test_questions (question, expected_outcome, expected_qa_id, style, set_name) VALUES (${q(t.question)}, ${q(t.expect ? "answer" : "fallback")}, ${t.expect ? qa.get(t.expect) : "NULL"}, ${q(t.style)}, ${q(t.set)});`,
  );
}
out.push(`INSERT INTO settings (name, value) VALUES ('answer_threshold', ${q(seed.thresholds.answer)}), ('suggest_threshold', ${q(seed.thresholds.suggest)});`);
out.push(`INSERT INTO admins (username, full_name, password_hash) VALUES ('admin', 'Knowledge Base Admin', ${q(bcrypt.hashSync("ebsu-admin-2026", 10))});`);
out.push("COMMIT;", "");

writeFileSync(join(ROOT, "database", "ebsu_chatbot.sql"), out.join("\n"));
console.log(`Wrote database/ebsu_chatbot.sql (${seed.entries.length} entries, ${seed.rules.length} rules, ${seed.tests.length} test questions).`);
